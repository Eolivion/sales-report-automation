"""Generate deliberately messy sales exports from three fictional stores.

Each store exports in its own format, the way real point-of-sale systems do:
different delimiters, column names, date formats and number formats, plus
duplicated rows, blank lines and a few broken values.
"""

import csv
import random
from datetime import date, timedelta
from pathlib import Path

from openpyxl import Workbook

OUT = Path(__file__).parent / "sample_data"

PRODUCTS = {
    "Wireless Mouse": 24.90,
    "Mechanical Keyboard": 89.00,
    "Laptop 14in": 1249.00,
    "USB-C Hub": 39.50,
    "Laptop Stand": 45.00,
    "Webcam HD": 59.90,
    "Headset Pro": 129.00,
    "External SSD 1TB": 119.00,
}
CUSTOMERS = [
    "Acme Corp", "Blue Ocean Ltd", "Greenfield Clinic", "Harbor Logistics",
    "Northwind Traders", "Pixel Studio", "Summit Accounting", "Vertex Labs",
]


def make_rows(rng, count):
    start = date(2026, 1, 1)
    rows = []
    for _ in range(count):
        product = rng.choice(list(PRODUCTS))
        rows.append([
            start + timedelta(days=rng.randrange(181)),
            product,
            rng.randint(1, 6),
            PRODUCTS[product],
            rng.choice(CUSTOMERS),
        ])
    return rows


def messy_name(rng, name):
    return rng.choice([name, name, name.upper(), name.lower(), f"  {name} "])


def with_duplicates(rng, rows, count):
    rows = rows + rng.sample(rows, count)
    rng.shuffle(rows)
    return rows


def write_north(rng):
    """Comma-separated, ISO dates, dot decimals."""
    rows = [
        [d.isoformat(), messy_name(rng, p), q, f"{price:.2f}", c]
        for d, p, q, price, c in make_rows(rng, 120)
    ]
    rows = with_duplicates(rng, rows, 4)
    rows[10][2] = ""       # missing quantity
    rows[57][0] = "N/A"    # broken date
    with open(OUT / "store_north.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["Date", "Product", "Qty", "Unit Price", "Customer"])
        writer.writerows(rows)


def write_south(rng):
    """Semicolon-separated, day-first dates, comma decimals (European export)."""
    def euro(value):
        return f"{value:,.2f}".replace(",", "_").replace(".", ",").replace("_", ".")

    rows = [
        [d.strftime("%d/%m/%Y"), messy_name(rng, p), q, euro(price), c]
        for d, p, q, price, c in make_rows(rng, 110)
    ]
    rows = with_duplicates(rng, rows, 3)
    rows[22][2] = "two"    # quantity typed as text
    with open(OUT / "store_south.csv", "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f, delimiter=";")
        writer.writerow(["order_date", "item", "quantity", "price", "client"])
        for i, row in enumerate(rows):
            writer.writerow(row)
            if i in (30, 75):
                f.write("\n")  # stray blank line


def write_east(rng):
    """Excel file with title rows above the header and currency typed as text."""
    rows = [
        [d.strftime("%b %d, %Y"), messy_name(rng, p), q, f"${price:,.2f}", c]
        for d, p, q, price, c in make_rows(rng, 100)
    ]
    rows = with_duplicates(rng, rows, 3)
    rows[15][1] = ""       # missing product
    rows[64][3] = "-"      # missing price

    workbook = Workbook()
    sheet = workbook.active
    sheet.append(["East Store - Sales Export"])
    sheet.append(["Generated by POS v2.3"])
    sheet.append([])
    sheet.append(["ORDER DATE", "PRODUCT NAME", "UNITS", "PRICE (USD)", "CUSTOMER NAME"])
    for i, row in enumerate(rows):
        sheet.append(row)
        if i in (20, 50):
            sheet.append([])  # stray blank row
    workbook.save(OUT / "store_east.xlsx")


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    rng = random.Random(2026)
    write_north(rng)
    write_south(rng)
    write_east(rng)
    print(f"Sample files written to {OUT}")
